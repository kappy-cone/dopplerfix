"""modeled_ratio (general model on the received axis) against the physics reference implementation."""
import numpy as np
import pytest

from doppler import physics as ph
from doppler import score, tracks
from doppler.geo import LocalFrame

FRAME = LocalFrame(40.0, -105.0, 0.0)
START = 1.7e9


def test_modeled_ratio_matches_physics_predicted_ratio():
    t = np.arange(0, 300, 0.25)
    enu = np.c_[70 * (t - 150), np.full_like(t, 400.0), 600 + 0 * t]
    tr = tracks.Track.from_enu("a", "A", START + t, enu, FRAME)
    v_ecef = np.gradient(tr.ecef(), tr.t_s, axis=0)
    from doppler.geo import enu_basis
    tr.vel_enu = np.einsum("nij,nj->ni", enu_basis(tr.lat_deg, tr.lon_deg), v_ecef)
    ts = tracks.build_trackset([tr], START, START + 300, 0.25)
    mic = np.array([0.0, 0.0, 1.5])
    t_rx = START + np.linspace(60, 240, 200)
    ratio, te, r, ok = score.modeled_ratio(FRAME.enu_to_ecef(mic), 0, ts, t_rx, 343.0)
    ref, te_ref, r_ref = ph.predicted_ratio_at(t_rx - START, t, enu, mic, 343.0)
    assert ok.all()
    np.testing.assert_allclose(te - START, te_ref, atol=2e-3)
    np.testing.assert_allclose(ratio, ref, atol=2e-5)
    # received-time identity
    np.testing.assert_allclose(te + r / 343.0, t_rx, atol=1e-6)


def test_profile_f0_closed_form():
    rho = np.linspace(1.1, 0.9, 50)
    assert score.profile_f0(133.0 * rho, rho) == pytest.approx(133.0)


def _two_track_setup(dt_true=1.7, noise=0.05, seed=0):
    """Two straight tracks, a mic, and ridges generated by the general model at true Δt (recording-relative)."""
    from doppler import cascade as cs

    rng = np.random.default_rng(seed)
    t = np.arange(0, 400, 0.25)
    tracks_ = []
    for k, (vx, vy, off, tc) in enumerate([(70, 0, 400, 120), (0, -60, -700, 280)]):
        enu = np.c_[vx * (t - tc) + (off if vy else 0), vy * (t - tc) + (0 if vy else off), 600 + 0 * t]
        tr = tracks.Track.from_enu(f"t{k}", f"T{k}", START + t, enu, FRAME)
        from doppler.geo import enu_basis
        tr.vel_enu = np.einsum("nij,nj->ni", enu_basis(tr.lat_deg, tr.lon_deg), np.gradient(tr.ecef(), tr.t_s, axis=0))
        tracks_.append(tr)
    ts = tracks.build_trackset(tracks_, START, START + 400, 0.25)
    mic = FRAME.enu_to_ecef(np.array([30.0, -20.0, 1.5]))
    evs = []
    for k, (f0, t_rx) in enumerate([(120.0, 120.0), (150.0, 280.0)]):
        tr_rel = np.arange(t_rx - 60, t_rx + 60, 0.1)
        ratio, _, _, ok = score.modeled_ratio(mic, k, ts, START + dt_true + tr_rel, 343.0)
        f = f0 * ratio + rng.normal(0, noise, len(ratio))
        evs.append(cs.ObservedEvent(k, 0, t_rx, 70.0, 700.0, f0, np.eye(3), (5.0, 5.0), tr_rel[ok], f[ok],
                                    np.full(ok.sum(), 1 / noise ** 2)))
    return ts, mic, evs


def test_scorer_recovers_shared_dt_and_each_f0():
    from doppler import cascade as cs

    ts, mic, evs = _two_track_setup()
    p = score.ScoreParams()
    res = score.score_hypotheses(evs, [cs.Hypothesis(1, (0, 1), (-5.0, 5.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert res.dt_s == pytest.approx(1.7, abs=0.02)
    assert res.f0_hz == pytest.approx([120.0, 150.0], rel=1e-4)
    assert np.all((res.rms_hz > 0.02) & (res.rms_hz < 0.05)) and res.n_missing.tolist() == [0, 0]  # medians of 5
    assert res.cost < 1.0                     # ≈ 0.5 for pure noise at σ
    # wrong assignment (tracks swapped) scores far worse
    bad = score.score_hypotheses(evs, [cs.Hypothesis(1, (1, 0), (-5.0, 5.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert bad.cost > 10 * res.cost


def test_scoring_is_locked_single_dt_for_all_events():
    """If one event's ridge is shifted in time by 3 s, a shared Δt cannot absorb it (independent t0s could)."""
    from dataclasses import replace

    from doppler import cascade as cs

    ts, mic, evs = _two_track_setup()
    p = score.ScoreParams()
    good = score.score_hypotheses(evs, [cs.Hypothesis(1, (0, 1), (-8.0, 8.0))], ts, {1: mic}, START, 343.0, p)[0]
    shifted = [evs[0], replace(evs[1], ridge_t_s=evs[1].ridge_t_s + 3.0)]
    lock = score.score_hypotheses(shifted, [cs.Hypothesis(1, (0, 1), (-8.0, 8.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert lock.cost > 20 * good.cost
    # each event alone would fit perfectly at its own Δt — the lock is what rejects it
    solo = score.score_hypotheses([shifted[1]], [cs.Hypothesis(1, (1,), (-8.0, 8.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert solo.cost < 1.0 and solo.dt_s == pytest.approx(1.7 - 3.0, abs=0.05)


def test_unmodelable_points_are_penalised():
    rho = np.ones(10)
    rho[:4] = np.nan
    c_all, *_ = score._event_cost(np.full(10, 100.0), np.ones(10), 0.1, 3.0)
    c_miss, _, _, miss = score._event_cost(np.full(10, 100.0), rho, 0.1, 3.0)
    assert miss == 4 and c_miss == pytest.approx(c_all + 4 * float(score.huber(np.array(9.0), 3.0)))


def test_refine_in_cell_moves_toward_the_mic():
    from doppler import cascade as cs

    ts, mic, evs = _two_track_setup()
    p = score.ScoreParams()
    B = score._cell_basis(mic)
    centre = mic - 70.0 * B[0] + 60.0 * B[1]          # cell centre 92 m from the mic
    res = score.rank_cells(evs, [(7, centre, [cs.Hypothesis(7, (0, 1), (-5.0, 5.0))])], ts, START, 343.0, p,
                           (-10.0, 10.0), 100.0)[0]
    assert res.refined and res.best.cost < res.score_centre
    assert np.linalg.norm(res.xyz_est - mic) < 15.0
    assert res.best.dt_s == pytest.approx(1.7, abs=0.05)


def test_ambiguity_unique_vs_spread_out_ties():
    p = score.ScoreParams(ambiguity_rel=0.15, ambiguity_radius_m=400.0)
    base = np.array([6.37e6, 0.0, 0.0])
    near = [base, base + [0, 150, 0], base + [0, 900, 0]]
    u = score.ambiguity([1.0, 1.1, 1.5], near, p)
    assert u["status"] == "unique" and u["n_tied"] == 2 and u["gap_ratio"] == pytest.approx(1.1)
    a = score.ambiguity([1.0, 1.05, 1.1], near, p)
    assert a["status"] == "ambiguous" and a["n_tied"] == 3 and a["spread_m"] == pytest.approx(900.0)
    assert score.ambiguity([], [], p)["status"] == "none"
