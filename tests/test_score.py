def _two_track_setup(dt_true=1.7, noise=0.05, seed=0):
    """Two straight tracks, a mic, and ridges generated by the general model at true Δt (recording-relative)."""
    from doppler import cascade as cs

    rng = np.random.default_rng(seed)
    t = np.arange(0, 400, 0.25)
    tracks_ = []
    for k, (vx, vy, off, tc) in enumerate([(70, 0, 400, 120), (0, -60, -700, 280)]):
        enu = np.c_[vx * (t - tc) + (off if vy else 0), vy * (t - tc) + (0 if vy else off), 600 + 0 * t]
        tr = tracks.Track.from_enu(f"t{k}", f"T{k}", START + t, enu, FRAME)
        from doppler.geo import enu_basis
        tr.vel_enu = np.einsum("nij,nj->ni", enu_basis(tr.lat_deg, tr.lon_deg), np.gradient(tr.ecef(), tr.t_s, axis=0))
        tracks_.append(tr)
    ts = tracks.build_trackset(tracks_, START, START + 400, 0.25)
    mic = FRAME.enu_to_ecef(np.array([30.0, -20.0, 1.5]))
    evs = []
    for k, (f0, t_rx) in enumerate([(120.0, 120.0), (150.0, 280.0)]):
        tr_rel = np.arange(t_rx - 60, t_rx + 60, 0.1)
        ratio, _, _, ok = score.modeled_ratio(mic, k, ts, START + dt_true + tr_rel, 343.0)
        f = f0 * ratio + rng.normal(0, noise, len(ratio))
        evs.append(cs.ObservedEvent(k, 0, t_rx, 70.0, 700.0, f0, np.eye(3), (5.0, 5.0), tr_rel[ok], f[ok],
                                    np.full(ok.sum(), 1 / noise ** 2)))
    return ts, mic, evs


def test_scorer_recovers_shared_dt_and_each_f0():
    from doppler import cascade as cs

    ts, mic, evs = _two_track_setup()
    p = score.ScoreParams()
    res = score.score_hypotheses(evs, [cs.Hypothesis(1, (0, 1), (-5.0, 5.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert res.dt_s == pytest.approx(1.7, abs=0.02)
    assert res.f0_hz == pytest.approx([120.0, 150.0], rel=1e-4)
    assert np.all((res.rms_hz > 0.02) & (res.rms_hz < 0.05)) and res.n_missing.tolist() == [0, 0]  # medians of 5
    assert res.cost < 1.0                     # ≈ 0.5 for pure noise at σ
    # wrong assignment (tracks swapped) scores far worse
    bad = score.score_hypotheses(evs, [cs.Hypothesis(1, (1, 0), (-5.0, 5.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert bad.cost > 10 * res.cost


def test_scoring_is_locked_single_dt_for_all_events():
    """If one event's ridge is shifted in time by 3 s, a shared Δt cannot absorb it (independent t0s could)."""
    from dataclasses import replace

    from doppler import cascade as cs

    ts, mic, evs = _two_track_setup()
    p = score.ScoreParams()
    good = score.score_hypotheses(evs, [cs.Hypothesis(1, (0, 1), (-8.0, 8.0))], ts, {1: mic}, START, 343.0, p)[0]
    shifted = [evs[0], replace(evs[1], ridge_t_s=evs[1].ridge_t_s + 3.0)]
    lock = score.score_hypotheses(shifted, [cs.Hypothesis(1, (0, 1), (-8.0, 8.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert lock.cost > 20 * good.cost
    # each event alone would fit perfectly at its own Δt — the lock is what rejects it
    solo = score.score_hypotheses([shifted[1]], [cs.Hypothesis(1, (1,), (-8.0, 8.0))], ts, {1: mic}, START, 343.0, p)[0]
    assert solo.cost < 1.0 and solo.dt_s == pytest.approx(1.7 - 3.0, abs=0.05)


